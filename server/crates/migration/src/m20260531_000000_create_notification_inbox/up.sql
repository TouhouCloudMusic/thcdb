)
WHERE comment_thread_id IS NOT NULL;

CREATE INDEX idx_notification_event_user_collection_id
ON public.notification_event (
  user_collection_id
)
WHERE user_collection_id IS NOT NULL;

CREATE TABLE public.account_role_changed_notification_event (
