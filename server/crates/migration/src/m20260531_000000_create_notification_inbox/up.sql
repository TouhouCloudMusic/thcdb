);

CREATE TABLE public.notification_entry (
  notification_id uuid NOT NULL,
  recipient_user_id integer NOT NULL,
  event_id bigint NOT NULL REFERENCES public.notification_event (id) ON DELETE RESTRICT,
  seq bigint NOT NULL,
  inbox_seq bigint NOT NULL,
  created_at timestamptz NOT NULL,
  PRIMARY KEY (notification_id, seq),
  CONSTRAINT fk_notification_entry_notification_recipient FOREIGN KEY (notification_id, recipient_user_id) REFERENCES public.notification (id, recipient_user_id) ON DELETE CASCADE,
  CONSTRAINT uq_notification_entry_event UNIQUE (notification_id, event_id),
  CONSTRAINT uq_notification_entry_recipient_inbox_seq UNIQUE (recipient_user_id, inbox_seq),
  CONSTRAINT ck_notification_entry_seq_positive CHECK (seq > 0),
  CONSTRAINT ck_notification_entry_inbox_seq_positive CHECK (inbox_seq > 0)
);

CREATE INDEX idx_notification_entry_event_id
ON public.notification_entry (
  event_id
);

CREATE INDEX idx_notification_entry_notification_inbox_seq
ON public.notification_entry (
  notification_id,
  inbox_seq
);

