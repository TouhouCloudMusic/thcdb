use std::fmt::Debug;

use argon2::password_hash;
use axum::http::StatusCode;
use sea_orm::DbErr;

use super::database::error::{DatabaseError, FkViolation};
use crate::shared::http::api_response::{self, AppError};
use crate::shared::types::BoxedError;

/// Note: Don't impl from for variants
#[derive(Debug, snafu::Snafu)]
pub enum Error {
    #[snafu(transparent)]
    Internal { source: BoxedError },
    #[snafu(transparent)]
    User { source: UserError },
}

impl Error {
    pub fn custom(message: &(impl ToString + ?Sized)) -> Self {
        Self::Internal {
            source: Box::new(CustomMsgError(message.to_string())),
        }
    }

    pub fn internal(
        err: impl std::error::Error + Send + Sync + 'static,
    ) -> Self {
        Self::Internal {
            source: Box::new(err),
        }
    }
}

#[derive(Debug)]
struct CustomMsgError(String);

impl std::fmt::Display for CustomMsgError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}", self.0)
    }
}

impl std::error::Error for CustomMsgError {}

// impl From<BoxedError> is generated by SNAFU due to the transparent variant

// Legacy bridge for slices that still return `infra::Error`.
// New database-facing code should use `DatabaseError` directly.
impl From<DbErr> for Error {
    fn from(err: DbErr) -> Self {
        Self::internal(
            DatabaseError::new(err)
                .with_operation("legacy infrastructure database operation"),
        )
    }
}

impl From<tokio::task::JoinError> for Error {
    fn from(err: tokio::task::JoinError) -> Self {
        Self::internal(err)
    }
}

impl From<std::io::Error> for Error {
    fn from(err: std::io::Error) -> Self {
        Self::internal(err)
    }
}

impl From<password_hash::Error> for Error {
    fn from(err: password_hash::Error) -> Self {
        Self::internal(err)
    }
}

impl Error {
    pub const fn status_code(&self) -> StatusCode {
        match self {
            Self::Internal { .. } => StatusCode::INTERNAL_SERVER_ERROR,
            Self::User { source } => source.status_code(),
        }
    }
}

impl axum::response::IntoResponse for Error {
    fn into_response(self) -> axum::response::Response {
        axum::response::IntoResponse::into_response(AppError::from(self))
    }
}

impl utoipa::IntoResponses for Error {
    fn responses() -> std::collections::BTreeMap<
        std::string::String,
        utoipa::openapi::RefOr<utoipa::openapi::response::Response>,
    > {
        api_response::Error::responses([
            StatusCode::INTERNAL_SERVER_ERROR,
            StatusCode::BAD_REQUEST,
        ])
        .into()
    }
}

#[derive(Debug, snafu::Snafu)]
pub enum UserError {
    #[snafu(transparent)]
    FkViolation { source: Box<FkViolation<DbErr>> },
}

impl UserError {
    pub const fn status_code(&self) -> StatusCode {
        match self {
            Self::FkViolation { .. } => StatusCode::BAD_REQUEST,
        }
    }
}
